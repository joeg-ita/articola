  if (typeof window === 'undefined') { if (typeof module !== 'undefined') module.exports = { EN: EN }; return; }

  function detect() {
    try { var v = localStorage.getItem(KEY); if (v === 'it' || v === 'en') return v; } catch (e) { /* private mode */ }
    var n = (navigator.languages && navigator.languages[0]) || navigator.language || 'it';
    return /^it\b/i.test(n) ? 'it' : 'en';
  }

  var lang = detect();
  document.documentElement.lang = lang;

  var I18N = {
    get lang() { return lang; },
    locale: function () { return lang === 'en' ? 'en-GB' : 'it-IT'; },
    set: function (l) {
      if (l !== 'it' && l !== 'en') return;
      lang = l;
      try { localStorage.setItem(KEY, l); } catch (e) { /* private mode */ }
      document.documentElement.lang = l;
    },
    t: function (s, vars) {
      if (typeof s !== 'string') return s;
      var out = (lang === 'en' && Object.prototype.hasOwnProperty.call(EN, s)) ? EN[s] : s;
      if (vars && typeof vars === 'object') out = out.replace(/\{(\w+)\}/g, function (m, k) { return k in vars ? String(vars[k]) : m; });
      return out;
    },
  };

  window.I18N = I18N;
